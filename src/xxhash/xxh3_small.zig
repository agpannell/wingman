pub fn hash128(input: []const u8, secret: *const [96]u8, seed: u64) u128 {
    const length = input.len;
    var low: u64 = undefined;
    var high: u64 = undefined;
    switch (length) {
        0 => {
            low = avalancheClassic(
                seed ^ readLittleEndian(u64, secret[64..]) ^ readLittleEndian(u64, secret[72..]),
            );
            high = avalancheClassic(
                seed ^ readLittleEndian(u64, secret[80..]) ^ readLittleEndian(u64, secret[88..]),
            );
        },
        1...3 => {
            const first: u32 = input[0];
            const middle: u32 = input[length / 2];
            const last: u32 = input[length - 1];
            const count: u32 = @intCast(length);
            const packed_bytes = last | (count << 8) | (first << 16) | (middle << 24);
            const opposite = std.math.rotl(u32, @byteSwap(packed_bytes), 13);
            const low_key: u64 = readLittleEndian(
                u32,
                secret[0..],
            ) ^ readLittleEndian(u32, secret[4..]);
            const high_key: u64 = readLittleEndian(
                u32,
                secret[8..],
            ) ^ readLittleEndian(u32, secret[12..]);
            low = avalancheClassic((low_key +% seed) ^ packed_bytes);
            high = avalancheClassic((high_key -% seed) ^ opposite);
        },
        4...8 => {
            const first: u64 = readLittleEndian(u32, input);
            const last: u64 = readLittleEndian(u32, input[length - 4 ..]);
            const seed_low: u32 = @truncate(seed);
            const changed_seed = seed ^ (@as(u64, @byteSwap(seed_low)) << 32);
            const key = (readLittleEndian(
                u64,
                secret[16..],
            ) ^ readLittleEndian(u64, secret[24..])) +% changed_seed;
            const combined = first | (last << 32);
            const multiplier = @as(u64, 0x9e3779b185ebca87) +% (@as(u64, @intCast(length)) << 2);
            const product: u128 = @as(u128, combined ^ key) * multiplier;
            low = @truncate(product);
            high = @truncate(product >> 64);
            high +%= low << 1;
            low ^= high >> 3;
            low ^= low >> 35;
            low *%= mixing_prime;
            low ^= low >> 28;
            high = avalancheXxh3(high);
        },
        9...16 => {
            const first = readLittleEndian(u64, input);
            const last = readLittleEndian(u64, input[length - 8 ..]);
            const first_key = (readLittleEndian(
                u64,
                secret[32..],
            ) ^ readLittleEndian(u64, secret[40..])) -% seed;
            const last_key = (readLittleEndian(
                u64,
                secret[48..],
            ) ^ readLittleEndian(u64, secret[56..])) +% seed;
            const keyed_first = first ^ last ^ first_key;
            const keyed_last = last ^ last_key;
            const product: u128 = @as(u128, keyed_first) * 0x9e3779b185ebca87;
            low = @truncate(product);
            high = @truncate(product >> 64);
            low +%= @as(u64, @intCast(length - 1)) << 54;
            const last_low: u32 = @truncate(keyed_last);
            high +%= keyed_last +% (@as(u64, last_low) *% (@as(u64, 0x85ebca77) - 1));
            low ^= @byteSwap(high);
            const second_product: u128 = @as(u128, low) * prime_2;
            low = avalancheXxh3(@truncate(second_product));
            const second_high: u64 = @truncate(second_product >> 64);
            high = avalancheXxh3(second_high +% high *% prime_2);
        },
        else => unreachable,
    }
    return (@as(u128, high) << 64) | low;
}

