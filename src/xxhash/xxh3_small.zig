//! XXH3 hashing for inputs up to 240 bytes. Algorithm design by Yann Collet and the xxHash
//! contributors; reference: https://github.com/Cyan4973/xxHash/tree/c87183a

const std = @import("std");
const testing = std.testing;

const prime_2: u64 = 0xc2b2ae3d27d4eb4f;
const prime_3: u64 = 0x165667b19e3779f9;
const mixing_prime: u64 = 0x9fb21c651e98df25;
const avalanche_prime: u64 = 0x165667919e3779f9;

fn readLittleEndian(comptime T: type, bytes: []const u8) T {
    return std.mem.readInt(T, bytes[0..@sizeOf(T)], .little);
}

fn avalancheClassic(value: u64) u64 {
    var mixed = value ^ (value >> 33);
    mixed *%= prime_2;
    mixed ^= mixed >> 29;
    mixed *%= prime_3;
    return mixed ^ (mixed >> 32);
}

fn avalancheXxh3(value: u64) u64 {
    const scrambled = (value ^ (value >> 37)) *% avalanche_prime;
    return scrambled ^ (scrambled >> 32);
}

// The caller validates the full secret before selecting a length regime. Keep the short helper
// entry aligned as the surrounding medium code changes size.
pub fn hash64(input: []const u8, secret: *const [96]u8, seed: u64) align(32) u64 {
    const length = input.len;
    return switch (length) {
        0 => avalancheClassic(
            seed ^ readLittleEndian(u64, secret[56..]) ^ readLittleEndian(u64, secret[64..]),
        ),
        1...3 => short: {
            const first: u32 = input[0];
            const middle: u32 = input[length / 2];
            const last: u32 = input[length - 1];
            const count: u32 = @intCast(length);
            const packed_bytes = last | (count << 8) | (first << 16) | (middle << 24);
            const secret_bits: u64 = readLittleEndian(
                u32,
                secret[0..],
            ) ^ readLittleEndian(u32, secret[4..]);
            break :short avalancheClassic((secret_bits +% seed) ^ packed_bytes);
        },
        4...8 => short: {
            const first: u64 = readLittleEndian(u32, input);
            const last: u64 = readLittleEndian(u32, input[length - 4 ..]);
            const combined = last | (first << 32);
            const seed_low: u32 = @truncate(seed);
            const changed_seed = seed ^ (@as(u64, @byteSwap(seed_low)) << 32);
            const secret_bits = readLittleEndian(
                u64,
                secret[8..],
            ) ^ readLittleEndian(u64, secret[16..]);
            const keyed = combined ^ (secret_bits -% changed_seed);
            var mixed = keyed ^ std.math.rotl(u64, keyed, 49) ^ std.math.rotl(u64, keyed, 24);
            mixed *%= mixing_prime;
            mixed ^= (mixed >> 35) +% length;
            mixed *%= mixing_prime;
            break :short mixed ^ (mixed >> 28);
        },
        9...16 => short: {
            const first = readLittleEndian(u64, input);
            const last = readLittleEndian(u64, input[length - 8 ..]);
            const first_key = (readLittleEndian(
                u64,
                secret[24..],
            ) ^ readLittleEndian(u64, secret[32..])) +% seed;
            const last_key = (readLittleEndian(
                u64,
                secret[40..],
            ) ^ readLittleEndian(u64, secret[48..])) -% seed;
            const low = first ^ first_key;
            const high = last ^ last_key;
            const product: u128 = @as(u128, low) * high;
            const product_low: u64 = @truncate(product);
            const product_high: u64 = @truncate(product >> 64);
            const folded = product_low ^ product_high;
            const mixed = @as(u64, @intCast(length)) +% @byteSwap(low) +% high +% folded;
            break :short avalancheXxh3(mixed);
        },
        else => unreachable,
    };
}

