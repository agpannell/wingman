const prime1: u64 = 0x9e3779b185ebca87;
const prime2: u64 = 0xc2b2ae3d27d4eb4f;
const prime4: u64 = 0x85ebca77c2b2ae63;

fn read64Le(bytes: []const u8) u64 {
    return std.mem.readInt(u64, bytes[0..8], .little);
}

fn avalanche(value: u64) u64 {
    const mixed = (value ^ (value >> 37)) *% avalanche_prime;
    return mixed ^ (mixed >> 32);
}

fn mixChunkWithSecret(data: *const [16]u8, secret: *const [16]u8, seed: u64) u64 {
    const first = read64Le(data) ^ (read64Le(secret) +% seed);
    const second = read64Le(data[8..]) ^ (read64Le(secret[8..]) -% seed);
    const product: u128 = @as(u128, first) * second;
    const low: u64 = @truncate(product);
    const high: u64 = @truncate(product >> 64);
    return low ^ high;
}

const PairAccumulator = struct {
    low: u64,
    high: u64,

    fn mixPair(
        self: *PairAccumulator,
        front: *const [16]u8,
        back: *const [16]u8,
        secret: *const [32]u8,
        seed: u64,
    ) void {
        self.low +%= mixChunkWithSecret(front, secret[0..16], seed);
        self.low ^= read64Le(back) +% read64Le(back[8..]);
        self.high +%= mixChunkWithSecret(back, secret[16..32], seed);
        self.high ^= read64Le(front) +% read64Le(front[8..]);
    }
};

const HashWords = struct { low: u64, high: u64 };

pub fn hash(comptime result_bits: u8, input: []const u8, secret: []const u8, seed: u64) HashWords {
    if (result_bits != 64 and result_bits != 128) @compileError(
        "XXH3 result width must be 64 or 128",
    );
    const length = input.len;
    std.debug.assert(length >= 17 and length <= 240 and secret.len >= 136);
    const size: u64 = @intCast(length);
    var lanes: PairAccumulator = .{ .low = size *% prime1, .high = 0 };
    if (length <= 128) {
        // The first and last chunks may overlap; each pair still contributes to the digest. At most
        // four pairs contribute; retain their descending order for the wide digest.
        inline for (.{ 3, 2, 1, 0 }) |pair| {
            if (length > pair * 32) {
                const front = input[pair * 16 ..][0..16];
                const back = input[length - 16 * (pair + 1) ..][0..16];
                const secret_pair = secret[pair * 32 ..][0..32];
                if (result_bits == 128) lanes.mixPair(front, back, secret_pair, seed) else {
                    lanes.low +%= mixChunkWithSecret(front, secret_pair[0..16], seed);
                    lanes.low +%= mixChunkWithSecret(back, secret_pair[16..32], seed);
                }
            }
        }
    } else if (result_bits == 128) {
        for (0..4) |index| {
            const offset = index * 32;
            lanes.mixPair(
                input[offset..][0..16],
                input[offset + 16 ..][0..16],
                secret[offset..][0..32],
                seed,
            );
        }
        lanes.low = avalanche(lanes.low);
        lanes.high = avalanche(lanes.high);
        const pairs = length / 32;
        for (4..pairs) |index| {
            const input_offset = index * 32;
            const key_offset = (index - 4) * 32 + 3;
            lanes.mixPair(
                input[input_offset..][0..16],
                input[input_offset + 16 ..][0..16],
                secret[key_offset..][0..32],
                seed,
            );
        }
        lanes.mixPair(
            input[length - 16 ..][0..16],
            input[length - 32 ..][0..16],
            secret[103..][0..32],
            0 -% seed,
        );
    } else {
        for (0..8) |index| {
            const offset = index * 16;
            lanes.low +%= mixChunkWithSecret(input[offset..][0..16], secret[offset..][0..16], seed);
        }
        lanes.low = avalanche(lanes.low);
        // Keep the final chunk's mix independent of the earlier lanes so the processor can overlap
        // their work before the final avalanche.
        var tail_mix = mixChunkWithSecret(input[length - 16 ..][0..16], secret[119..][0..16], seed);
        for (8..length / 16) |index| {
            const input_offset = index * 16;
            const key_offset = (index - 8) * 16 + 3;
            tail_mix +%= mixChunkWithSecret(
                input[input_offset..][0..16],
                secret[key_offset..][0..16],
                seed,
            );
        }
        lanes.low +%= tail_mix;
    }
    if (result_bits == 64) return .{ .low = avalanche(lanes.low), .high = 0 };
    const low = avalanche(lanes.low +% lanes.high);
    const high_input = lanes.low *% prime1 +% lanes.high *% prime4 +% (size -% seed) *% prime2;
    return .{ .low = low, .high = 0 -% avalanche(high_input) };
}

// A complete custom-secret call has seed zero. At 97–128 bytes all four front/back pairs
// contribute, even when they overlap, so this path avoids per-pair selection and seed adjustment.
pub noinline fn hashSecret97To128(input: []const u8, secret: []const u8) u128 {
    std.debug.assert(input.len >= 97 and input.len <= 128 and secret.len >= 136);
    const size: u64 = @intCast(input.len);
    var lanes: PairAccumulator = .{ .low = size *% prime1, .high = 0 };
    inline for (.{ 3, 2, 1, 0 }) |pair| {
        const front = input[pair * 16 ..][0..16];
        const back = input[input.len - 16 * (pair + 1) ..][0..16];
        const secret_pair = secret[pair * 32 ..][0..32];
        lanes.mixPair(front, back, secret_pair, 0);
    }
    const low = avalanche(lanes.low +% lanes.high);
    const high_input = lanes.low *% prime1 +% lanes.high *% prime4 +% size *% prime2;
    const high = 0 -% avalanche(high_input);
    return (@as(u128, high) << 64) | low;
}

